print(f"Cardinalidades:       {CAT_CARDINALITIES}")
print(f"Pesos de clase:       {CLASS_WEIGHTS}")

"""## Construir DataLoaders"""

BATCH_SIZE = 256

def make_loader(num, cat, y, shuffle=True):
    ds = TensorDataset(
        torch.tensor(num),
        torch.tensor(cat),
        torch.tensor(y)
    )
    return DataLoader(ds, batch_size=BATCH_SIZE, shuffle=shuffle)

train_loader = make_loader(X_train_num, X_train_cat, y_train, shuffle=True)
val_loader   = make_loader(X_val_num,   X_val_cat,   y_val,   shuffle=False)
test_loader  = make_loader(X_test_num,  X_test_cat,  y_test,  shuffle=False)

print(f"Batches en train: {len(train_loader)}")
print(f"Batches en val:   {len(val_loader)}")
print(f"DataLoaders listos")

"""## Definir el modelo FT-Transformer

El FT-Transformer (Gorishniy et al., 2021) tiene dos componentes principales:

1. **Feature Tokenizer**: convierte cada feature en un vector de dimensión `d_block`
   - Features numéricas → proyección lineal
   - Features categóricas → tabla de embeddings aprendible
2. **Transformer blocks**: aplican self-attention entre los tokens de features

Usamos `get_default_kwargs()` para cargar exactamente la configuración reportada
en el paper original para datasets de tamaño mediano.

"""

# Inspeccionar los hiperparámetros por defecto del paper
defaults = rtdl.FTTransformer.get_default_kwargs()
print("Hiperparámetros del paper (Gorishniy et al., 2021):")
for k, v in defaults.items():
    if not k.startswith("_"):
        print(f"  {k:30s}: {v}")

# Construir el modelo
model = rtdl.FTTransformer(
    n_cont_features  = N_NUM_FEATURES,
    cat_cardinalities= CAT_CARDINALITIES,
    **defaults,        # n_blocks=3, d_block=192, attention_n_heads=8, ...
    d_out            = 1,   # Clasificación binaria: default / no default
)

model = model.to(DEVICE)

# Conteo de parámetros
n_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
print(f"\nParámetros entrenables: {n_params:,}")
print(f"Modelo en dispositivo:  {DEVICE}")

# Verificar forward pass con un mini-batch de prueba
x_num_test = torch.randn(4, N_NUM_FEATURES).to(DEVICE)
x_cat_test = torch.zeros(4, len(CAT_CARDINALITIES), dtype=torch.long).to(DEVICE)
with torch.no_grad():
    out_test = model(x_num_test, x_cat_test)
print(f"Forward pass OK — output shape: {out_test.shape}")

"""##  Configurar optimizer, scheduler y función de pérdida"""

# Función de pérdida con peso de clase
# Penalizamos más los errores en la clase minoritaria (defaulters)
pos_weight = torch.tensor(
    [CLASS_WEIGHTS[1] / CLASS_WEIGHTS[0]],
    dtype=torch.float32
).to(DEVICE)

criterion = nn.BCEWithLogitsLoss(pos_weight=pos_weight)

# Optimizer: AdamW con weight decay
# El paper original recomienda lr=1e-4 y weight_decay=1e-5 para FT-Transformer
optimizer = torch.optim.AdamW(
    model.parameters(),
    lr=1e-4,
    weight_decay=1e-5
)

# Reduce el lr si la val loss no mejora en 5 épocas
scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
    optimizer,
    mode="min",
    factor=0.5,
    patience=5

)

print("Optimizer: AdamW (lr=1e-4, weight_decay=1e-5)")
print("Scheduler: ReduceLROnPlateau (factor=0.5, patience=5)")
print(f"pos_weight para BCEWithLogitsLoss: {pos_weight.item():.4f}")

"""## Loop de entrenamiento con Early Stopping"""

N_EPOCHS      = 50
PATIENCE      = 10
BEST_VAL_LOSS = float("inf")
PATIENCE_CTR  = 0
BEST_EPOCH    = 0

history = {"train_loss": [], "val_loss": [], "val_auc": []}

print(f"Entrenando por hasta {N_EPOCHS} épocas con early stopping (patience={PATIENCE})")
print(f"{'Época':>6} | {'Train Loss':>10} | {'Val Loss':>10} | {'Val AUC':>8} | {'LR':>8}")
print("-" * 55)

for epoch in range(1, N_EPOCHS + 1):

    # Fase de entrenamiento
    model.train()
    train_losses = []
    for x_num, x_cat, y_batch in train_loader:
        x_num   = x_num.to(DEVICE)
        x_cat   = x_cat.to(DEVICE)
        y_batch = y_batch.to(DEVICE)

        optimizer.zero_grad()
        logits = model(x_num, x_cat).squeeze(1)
        loss   = criterion(logits, y_batch)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        train_losses.append(loss.item())

    # Fase de validación
    model.eval()
    val_losses, val_probs, val_labels = [], [], []
    with torch.no_grad():
        for x_num, x_cat, y_batch in val_loader:
            x_num   = x_num.to(DEVICE)
            x_cat   = x_cat.to(DEVICE)
            y_batch = y_batch.to(DEVICE)
            logits  = model(x_num, x_cat).squeeze(1)
            loss    = criterion(logits, y_batch)
            val_losses.append(loss.item())
            val_probs.extend(torch.sigmoid(logits).cpu().numpy())
            val_labels.extend(y_batch.cpu().numpy())

    train_loss = np.mean(train_losses)
    val_loss   = np.mean(val_losses)
    val_auc    = roc_auc_score(val_labels, val_probs)
    current_lr = optimizer.param_groups[0]["lr"]

    history["train_loss"].append(train_loss)
    history["val_loss"].append(val_loss)
    history["val_auc"].append(val_auc)

    scheduler.step(val_loss)

    # Guardar mejor modelo
    if val_loss < BEST_VAL_LOSS:
        BEST_VAL_LOSS = val_loss
        BEST_EPOCH    = epoch
        PATIENCE_CTR  = 0
        torch.save(model.state_dict(), "ft_transformer_best.pt")
    else:
        PATIENCE_CTR += 1

    if epoch % 5 == 0 or epoch == 1 :
        print(f"{epoch:>6} | {train_loss:>10.4f} | {val_loss:>10.4f} | "
              f"{val_auc:>8.4f} | {current_lr:>8.2e}")

    # Early stopping
    if PATIENCE_CTR >= PATIENCE:
        print(f"\nEarly stopping en época {epoch}. Mejor época: {BEST_EPOCH}")
        break

print(f"\nEntrenamiento completado. Mejor val_loss: {BEST_VAL_LOSS:.4f} (época {BEST_EPOCH})")

"""## Curvas de aprendizaje"""

