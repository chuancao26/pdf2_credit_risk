# 3. Wrapper Predictivo por Lotes
def predict_wrapper_batched(X_combined):
    batch_size = 81920
    n_samples = X_combined.shape[0]
    all_probs = []

    for i in range(0, n_samples, batch_size):
        batch = X_combined[i:i + batch_size]

        x_n = batch[:, :N_NUM_FEATURES].astype(np.float32)
        x_c = batch[:, N_NUM_FEATURES:].astype(np.int64)

        t_num = torch.tensor(x_n).to(DEVICE)
        t_cat = torch.tensor(x_c).to(DEVICE)

        with torch.no_grad():
            logits = model(t_num, t_cat).squeeze(1)
            probs = torch.sigmoid(logits)

        all_probs.extend(probs.cpu().numpy())

        del t_num, t_cat, logits, probs

    return np.array(all_probs)

# 4. Inicializar KernelExplainer
print("Construyendo el explicador agnostico...")
explainer = shap.KernelExplainer(predict_wrapper_batched, bg_summary)

